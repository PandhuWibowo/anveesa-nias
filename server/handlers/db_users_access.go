// ── DB Users & Grants: plans, preview, approval ───────────────────
//
// Every grant change (the privilege matrix and the "Grant access" wizard) is
// first turned into a plan: the exact SQL statements, grouped by the database
// they must run in (PostgreSQL GRANTs on schemas/tables only work from inside
// that database). A plan can then be previewed, applied directly, or submitted
// as an approval request that runs the same statements once approved.

// grantBatch is a group of statements that run together in one database.
// Database is empty for MySQL/MariaDB (grants name the database themselves).
type grantBatch struct {
	Database   string   `json:"database,omitempty"`
	Statements []string `json:"statements"`
}

// dbAccessRequestOpts selects what to do with a plan.
//   - mode "preview": return the SQL and whether approval is required
//   - mode "request": submit the SQL as approval request(s)
//   - mode "apply" (default): execute now (refused with 409 when approval is required)
type dbAccessRequestOpts struct {
	Mode        string `json:"mode"`
	WorkflowID  int64  `json:"workflow_id"`
	Title       string `json:"title"`
	Description string `json:"description"`
}

// dbAccessScriptHeader marks an approval request generated by DB Users & Grants.
// The approval executor runs it statement by statement inside the named
// database instead of as one blob against the connection's default database.
const dbAccessScriptHeader = "-- nias:db-access"

func countStatements(batches []grantBatch) int {
	n := 0
	for _, b := range batches {
		n += len(b.Statements)
	}
	return n
}

// safeObjName rejects names that cannot be written on one script line.
func safeObjName(s string) bool {
	return s != "" && len(s) <= 256 && !strings.ContainsAny(s, "\r\n\x00")
}

// ── PostgreSQL: per-database helpers ──────────────────────────────

func pgCurrentDatabase(ctx context.Context, db *sql.DB) string {
	var name string
	_ = db.QueryRowContext(ctx, `SELECT current_database()`).Scan(&name)
	return name
}

// connUsesSSH reports whether the connection goes through an SSH tunnel.
// openTempConn cannot follow the tunnel, so such connections are limited to
// the database they are configured for.
func connUsesSSH(connID int64) bool {
	var host string
	_ = appdb.DB.QueryRow(appdb.ConvertQuery(`SELECT COALESCE(ssh_host,'') FROM connections WHERE id=?`), connID).Scan(&host)
	return strings.TrimSpace(host) != ""
}

// withConnDatabase runs fn against target: the pooled connection when target is
// empty or is the connection's own database, otherwise a short-lived
// connection to that database on the same server (PostgreSQL only).
func withConnDatabase(ctx context.Context, connID int64, defaultDB *sql.DB, driver, target string, fn func(*sql.DB) error) error {
	if driver != "postgres" || target == "" || target == pgCurrentDatabase(ctx, defaultDB) {
		return fn(defaultDB)
	}
	if connUsesSSH(connID) {
		return fmt.Errorf("this connection uses an SSH tunnel, so only its own database can be managed; database %q is on the same server but not reachable from here", target)
	}
	tc, _, err := openTempConn(connID, target)
	if err != nil {
		return fmt.Errorf("cannot connect to database %q: %w", target, err)
	}
	defer tc.Close()
	return fn(tc)
}

// pgForEachDatabase calls fn for the connection's own database and, best
// effort, for every other database on the server the connection can reach.
// Databases that cannot be opened are skipped.
func pgForEachDatabase(ctx context.Context, connID int64, defaultDB *sql.DB, fn func(ctx context.Context, db *sql.DB, dbName string)) {
	cur := pgCurrentDatabase(ctx, defaultDB)
	fn(ctx, defaultDB, cur)
	if connUsesSSH(connID) {
		return
	}

	rows, err := defaultDB.QueryContext(ctx, `
		SELECT datname FROM pg_database
		WHERE NOT datistemplate AND datallowconn
		  AND datname <> current_database()
		  AND has_database_privilege(current_user, datname, 'CONNECT')
		ORDER BY datname
		LIMIT 50
	`)
	if err != nil {
		return
	}
	var others []string
	for rows.Next() {
		var n string
		if rows.Scan(&n) == nil && n != "" {
			others = append(others, n)
		}
	}
	rows.Close()

	var wg sync.WaitGroup
	sem := make(chan struct{}, 4)
	for _, name := range others {
		wg.Add(1)
		go func(name string) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			cctx, cancel := context.WithTimeout(ctx, 8*time.Second)
			defer cancel()
			tc, _, err := openTempConn(connID, name)
			if err != nil {
				return
			}
			defer tc.Close()
			if err := tc.PingContext(cctx); err != nil {
				return
			}
			fn(cctx, tc, name)
		}(name)
	}
	wg.Wait()
}

// pgGetGrantsAllDBs returns the user's grants across every reachable database.
// Schema/table/sequence/function entries carry the database they live in, so
// the editor and the diff can tell "public" in one database from another.
func pgGetGrantsAllDBs(ctx context.Context, connID int64, defaultDB *sql.DB, username string) ([]GrantEntry, error) {
	var mu sync.Mutex
	var out []GrantEntry
	var firstErr error
	cur := pgCurrentDatabase(ctx, defaultDB)

	pgForEachDatabase(ctx, connID, defaultDB, func(ctx context.Context, db *sql.DB, dbName string) {
		g, err := pgGetGrants(ctx, db, username)
		mu.Lock()
		defer mu.Unlock()
		if err != nil {
			if dbName == cur && firstErr == nil {
				firstErr = err
			}
			return
		}
		for _, e := range g {
			if e.Level == "database" {
				// Database-level privileges are server-wide; read them once.
				if dbName != cur {
					continue
				}
			} else {
				e.Database = dbName
			}
			out = append(out, e)
		}
	})
	if firstErr != nil {
		return nil, firstErr
	}

	rank := map[string]int{"database": 0, "schema": 1, "table": 2, "sequence": 3, "function": 4}
	sort.SliceStable(out, func(i, j int) bool {
		a, b := out[i], out[j]
		if rank[a.Level] != rank[b.Level] {
			return rank[a.Level] < rank[b.Level]
		}
		if a.Database != b.Database {
			return a.Database < b.Database
		}
		if a.Schema != b.Schema {
			return a.Schema < b.Schema
		}
		return a.Table < b.Table
	})
	return out, nil
}

// planPGGrantChanges diffs the desired grants against the current ones and
// returns the GRANT/REVOKE statements, grouped by the database they run in.
func planPGGrantChanges(ctx context.Context, connID int64, defaultDB *sql.DB, username string, desired []GrantEntry) ([]grantBatch, error) {
	current, err := pgGetGrantsAllDBs(ctx, connID, defaultDB, username)
	if err != nil {
		return nil, err
	}
	cur := pgCurrentDatabase(ctx, defaultDB)

	type key struct{ level, database, schema, table string }
	norm := func(g GrantEntry) key {
		db := g.Database
		if g.Level != "database" && db == "" {
			db = cur
		}
		return key{g.Level, db, g.Schema, g.Table}
	}

	allowed := mergeMaps(pgTablePrivileges, pgSchemaPrivileges, pgDatabasePrivileges, pgSequencePrivileges, pgFunctionPrivileges)
	currentMap := make(map[key]map[string]bool)
	for _, g := range current {
		currentMap[norm(g)] = toPrivSet(g.Privileges)
	}
	desiredMap := make(map[key]map[string]bool)
	for _, g := range desired {
		k := norm(g)
		set := toPrivSet(filterAllowedPrivs(g.Privileges, allowed))
		if prev, ok := desiredMap[k]; ok {
			for p := range prev {
				set[p] = true
			}
		}
		desiredMap[k] = set
	}

	keys := make(map[key]bool)
	for k := range currentMap {
		keys[k] = true
	}
	for k := range desiredMap {
		keys[k] = true
	}
	ordered := make([]key, 0, len(keys))
	for k := range keys {
		ordered = append(ordered, k)
	}
	rank := map[string]int{"database": 0, "schema": 1, "table": 2, "sequence": 3, "function": 4}
	sort.Slice(ordered, func(i, j int) bool {
		a, b := ordered[i], ordered[j]
		if rank[a.level] != rank[b.level] {
			return rank[a.level] < rank[b.level]
		}
		if a.database != b.database {
			return a.database < b.database
		}
		if a.schema != b.schema {
			return a.schema < b.schema
		}
		return a.table < b.table
	})

	byDB := map[string][]string{}
	var dbOrder []string
	add := func(db, stmt string) {
		if _, ok := byDB[db]; !ok {
			dbOrder = append(dbOrder, db)
		}
		byDB[db] = append(byDB[db], stmt)
	}

	for _, k := range ordered {
		cp, dp := currentMap[k], desiredMap[k]
		var toGrant, toRevoke []string
		for p := range dp {
			if !cp[p] {
				toGrant = append(toGrant, p)
			}
		}
		for p := range cp {
			if !dp[p] {
				toRevoke = append(toRevoke, p)
			}
		}
		sort.Strings(toGrant)
		sort.Strings(toRevoke)

		entry := GrantEntry{Level: k.level, Database: k.database, Schema: k.schema, Table: k.table}
		if k.level != "database" && (!safeObjName(k.schema) || (k.level != "schema" && !safeObjName(k.table))) {
			continue
		}
		if k.level == "database" && !safeObjName(k.database) {
			continue
		}
		execDB := k.database
		if k.level == "database" {
			execDB = cur // database-level grants run from the connection's own database
		}
		if len(toGrant) > 0 {
			if stmt, err := buildPGGrantStmt(true, username, entry, toGrant); err == nil {
				add(execDB, stmt)
			}
		}
		if len(toRevoke) > 0 {
			if stmt, err := buildPGGrantStmt(false, username, entry, toRevoke); err == nil {
				add(execDB, stmt)
			}
		}
	}

	batches := make([]grantBatch, 0, len(dbOrder))
	for _, db := range dbOrder {
		batches = append(batches, grantBatch{Database: db, Statements: byDB[db]})
	}
	return batches, nil
}

// planMySQLGrantChanges is the MySQL/MariaDB counterpart of planPGGrantChanges.
func planMySQLGrantChanges(ctx context.Context, db *sql.DB, username, host string, desired []GrantEntry) ([]grantBatch, error) {
	current, err := mysqlGetGrants(ctx, db, username, host)
	if err != nil {
		return nil, err
	}

	type key struct{ level, database, table string }
	currentMap := make(map[key]map[string]bool)
	for _, g := range current {
		currentMap[key{g.Level, g.Database, g.Table}] = toPrivSet(g.Privileges)
	}
	desiredMap := make(map[key]map[string]bool)
	for _, g := range desired {
		desiredMap[key{g.Level, g.Database, g.Table}] = toPrivSet(filterAllowedPrivs(g.Privileges, mysqlPrivileges))
	}

	keys := make(map[key]bool)
	for k := range currentMap {
		keys[k] = true
	}
	for k := range desiredMap {
		keys[k] = true
	}
	ordered := make([]key, 0, len(keys))
	for k := range keys {
		ordered = append(ordered, k)
	}
	sort.Slice(ordered, func(i, j int) bool {
		a, b := ordered[i], ordered[j]
		if a.level != b.level {
			return a.level < b.level
		}
		if a.database != b.database {
			return a.database < b.database
		}
		return a.table < b.table
	})

	userSpec := fmt.Sprintf("'%s'@'%s'", escapeMySQL(username), escapeMySQL(host))
	var stmts []string
	for _, k := range ordered {
		if (k.database != "" && !safeObjName(k.database)) || (k.table != "" && !safeObjName(k.table)) {
			continue
		}
		cp, dp := currentMap[k], desiredMap[k]
		var toGrant, toRevoke []string
		for p := range dp {
			if !cp[p] {
				toGrant = append(toGrant, p)
			}
		}
		for p := range cp {
			if !dp[p] {
				toRevoke = append(toRevoke, p)
			}
		}
		sort.Strings(toGrant)
		sort.Strings(toRevoke)
		target := mysqlGrantTarget(k.level, k.database, k.table)
		if len(toGrant) > 0 {
			stmts = append(stmts, fmt.Sprintf("GRANT %s ON %s TO %s", strings.Join(toGrant, ", "), target, userSpec))
		}
		if len(toRevoke) > 0 {
			stmts = append(stmts, fmt.Sprintf("REVOKE %s ON %s FROM %s", strings.Join(toRevoke, ", "), target, userSpec))
		}
	}
	if len(stmts) == 0 {
		return nil, nil
	}
	return []grantBatch{{Statements: stmts}}, nil
}

// execGrantBatches runs each batch in its database. PostgreSQL batches run in
// one transaction so a failing statement leaves that database unchanged.
func execGrantBatches(ctx context.Context, connID int64, defaultDB *sql.DB, driver string, batches []grantBatch) error {
	for _, b := range batches {
		if len(b.Statements) == 0 {
			continue
		}
		err := withConnDatabase(ctx, connID, defaultDB, driver, b.Database, func(db *sql.DB) error {
			if driver == "postgres" {
				tx, err := db.BeginTx(ctx, nil)
				if err != nil {
					return err
				}
				for _, stmt := range b.Statements {
					if _, err := tx.ExecContext(ctx, stmt); err != nil {
						tx.Rollback()
						return fmt.Errorf("failed to execute %q: %w", stmt, err)
					}
				}
				return tx.Commit()
			}
			for _, stmt := range b.Statements {
				if _, err := db.ExecContext(ctx, stmt); err != nil {
					return fmt.Errorf("failed to execute %q: %w", stmt, err)
				}
			}
			return nil
		})
		if err != nil {
			return err
		}
	}
	if driver == "mysql" || driver == "mariadb" {
		defaultDB.ExecContext(ctx, "FLUSH PRIVILEGES")
	}
	return nil
}

// ── Approval script ───────────────────────────────────────────────

func buildDBAccessScript(b grantBatch) string {
	var sb strings.Builder
	sb.WriteString(dbAccessScriptHeader)
	if b.Database != "" {
		sb.WriteString(" database=")
		sb.WriteString(b.Database)
	}
	sb.WriteString("\n-- Generated by DB Users & Grants. Runs one statement per line")
	if b.Database != "" {
		sb.WriteString(" inside database ")
		sb.WriteString(b.Database)
	}
	sb.WriteString(".\n")
	for _, s := range b.Statements {
		sb.WriteString(s)
		sb.WriteString(";\n")
	}
	return sb.String()
}

// parseDBAccessScript recognises a script made by buildDBAccessScript.
func parseDBAccessScript(statement string) (grantBatch, bool) {
	lines := strings.Split(strings.ReplaceAll(statement, "\r\n", "\n"), "\n")
	if len(lines) == 0 || !strings.HasPrefix(strings.TrimSpace(lines[0]), dbAccessScriptHeader) {
		return grantBatch{}, false
	}
	var b grantBatch
	head := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(lines[0]), dbAccessScriptHeader))
	if strings.HasPrefix(head, "database=") {
		b.Database = strings.TrimSpace(strings.TrimPrefix(head, "database="))
	}
	for _, ln := range lines[1:] {
		ln = strings.TrimSpace(ln)
		if ln == "" || strings.HasPrefix(ln, "--") {
			continue
		}
		ln = strings.TrimSpace(strings.TrimSuffix(ln, ";"))
		if ln != "" {
			b.Statements = append(b.Statements, ln)
		}
	}
	return b, true
}

// runDBAccessScript executes an approved DB Users & Grants script.
func runDBAccessScript(ctx context.Context, connID int64, defaultDB *sql.DB, driver string, b grantBatch) error {
	if b.Database != "" && !safeObjName(b.Database) {
		return fmt.Errorf("invalid target database")
	}
	return execGrantBatches(ctx, connID, defaultDB, driver, []grantBatch{b})
}

// ── Approval state & response ─────────────────────────────────────

// dbAccessApprovalState mirrors the SQL editor rule: when approval workflows
// apply to this connection, non-admin users must go through approval.
// Admins may still submit a request on purpose (workflows are returned).
func dbAccessApprovalState(r *http.Request, connID int64) (bool, []ApprovalWorkflow, error) {
	if !isAuthEnabled() {
		return false, []ApprovalWorkflow{}, nil
	}
	userID, _, role := currentUserFromHeaders(r)
	if userID == 0 {
		return false, []ApprovalWorkflow{}, nil
	}
	wfs, err := findApplicableWorkflows(userID, role, connID)
	if err != nil {
		return false, nil, err
	}
	if wfs == nil {
		wfs = []ApprovalWorkflow{}
	}
	return role != "admin" && len(wfs) > 0, wfs, nil
}

func respondDBAccessPlan(w http.ResponseWriter, r *http.Request, connID int64, defaultDB *sql.DB, driver string, batches []grantBatch, opts dbAccessRequestOpts, defaultTitle string) {
	if batches == nil {
		batches = []grantBatch{}
	}
	required, workflows, err := dbAccessApprovalState(r, connID)
	if err != nil {
		http.Error(w, jsonError("failed to resolve approval workflows"), http.StatusInternalServerError)
		return
	}

	switch opts.Mode {
	case "preview":
		json.NewEncoder(w).Encode(map[string]any{
			"batches":           batches,
			"approval_required": required,
			"workflows":         workflows,
		})
		return

	case "request":
		if countStatements(batches) == 0 {
			http.Error(w, jsonError("nothing to change"), http.StatusBadRequest)
			return
		}
		userID, username, role := currentUserFromHeaders(r)
		title := strings.TrimSpace(opts.Title)
		if title == "" {
			title = defaultTitle
		}
		var created []map[string]any
		for _, b := range batches {
			if len(b.Statements) == 0 {
				continue
			}
			t := title
			if len(batches) > 1 && b.Database != "" {
				t = fmt.Sprintf("%s (%s)", title, b.Database)
			}
			req, status, err := createApprovalRequestRecord(userID, username, role, CreateQueryApprovalRequest{
				Title:       t,
				Description: strings.TrimSpace(opts.Description),
				ConnID:      connID,
				Database:    b.Database,
				Statement:   buildDBAccessScript(b),
				WorkflowID:  opts.WorkflowID,
			})
			if err != nil {
				http.Error(w, jsonError(err.Error()), status)
				return
			}
			created = append(created, map[string]any{"id": req.ID, "title": req.Title})
		}
		json.NewEncoder(w).Encode(map[string]any{"status": "requested", "requests": created})
		return
	}

	// apply
	if countStatements(batches) == 0 {
		json.NewEncoder(w).Encode(map[string]any{"status": "unchanged", "batches": batches})
		return
	}
	if required {
		w.WriteHeader(http.StatusConflict)
		json.NewEncoder(w).Encode(map[string]any{
			"error":             "approval required before changing database grants",
			"approval_required": true,
			"workflows":         workflows,
			"batches":           batches,
		})
		return
	}

	start := time.Now()
	execErr := execGrantBatches(r.Context(), connID, defaultDB, driver, batches)
	var all []string
	for _, b := range batches {
		prefix := ""
		if b.Database != "" {
			prefix = "-- database " + b.Database + "\n"
		}
		all = append(all, prefix+strings.Join(b.Statements, ";\n")+";")
	}
	errMsg := ""
	if execErr != nil {
		errMsg = execErr.Error()
	}
	go WriteAuditLog(r.Header.Get("X-Username"), connID, connectionNameByID(connID), strings.Join(all, "\n"), time.Since(start).Milliseconds(), 0, errMsg)
	if execErr != nil {
		http.Error(w, jsonError(execErr.Error()), http.StatusInternalServerError)
		return
	}
	json.NewEncoder(w).Encode(map[string]any{"status": "applied", "batches": batches})
}

// ── Grant access wizard ───────────────────────────────────────────

type dbAccessRequest struct {
	dbAccessRequestOpts
	Host string `json:"host"`
	// Action: "grant" (default), "revoke" (schema-wide), "revoke_default" (one default-privileges entry)
	Action             string   `json:"action"`
	Database           string   `json:"database"`
	Schema             string   `json:"schema"`
	Preset             string   `json:"preset"` // readonly | readwrite | custom
	TablePrivileges    []string `json:"table_privileges"`
	SequencePrivileges []string `json:"sequence_privileges"`
	IncludeSequences   bool     `json:"include_sequences"`
	IncludeFuture      bool     `json:"include_future"`
	FutureForRoles     []string `json:"future_for_roles"`
	// revoke_default
	Owner      string `json:"owner"`
	ObjectType string `json:"object_type"` // r tables, S sequences, f functions, T types, n schemas
}

var pgDefaultACLObjects = map[string]string{"r": "TABLES", "S": "SEQUENCES", "f": "FUNCTIONS", "T": "TYPES", "n": "SCHEMAS"}

func accessPresetPrivs(driver string, req dbAccessRequest) (tables, sequences []string) {
	if driver == "postgres" {
		switch req.Preset {
		case "readwrite":
			return []string{"SELECT", "INSERT", "UPDATE", "DELETE"}, []string{"USAGE", "SELECT", "UPDATE"}
		case "custom":
			return filterAllowedPrivs(req.TablePrivileges, pgTablePrivileges), filterAllowedPrivs(req.SequencePrivileges, pgSequencePrivileges)
		default:
			return []string{"SELECT"}, []string{"USAGE", "SELECT"}
		}
	}
	switch req.Preset {
	case "readwrite":
		return []string{"SELECT", "INSERT", "UPDATE", "DELETE", "SHOW VIEW"}, nil
	case "custom":
		return filterAllowedPrivs(req.TablePrivileges, mysqlPrivileges), nil
	default:
		return []string{"SELECT", "SHOW VIEW"}, nil
	}
}

func planPGAccess(username string, req dbAccessRequest, cur string) ([]grantBatch, error) {
	user := quoteIdentPG(username)
	db := req.Database
	if db == "" {
		db = cur
	}
	if !safeObjName(db) {
		return nil, fmt.Errorf("database is required")
	}

	var roles []string
	for _, r := range req.FutureForRoles {
		r = strings.TrimSpace(r)
		if r == "" {
			continue
		}
		if !safeObjName(r) {
			return nil, fmt.Errorf("invalid role %q", r)
		}
		roles = append(roles, r)
	}
	forRole := func(r string) string {
		if r == "" {
			return ""
		}
		return " FOR ROLE " + quoteIdentPG(r)
	}
	if len(roles) == 0 {
		roles = []string{""} // objects created by the connection's own user
	}

	var stmts []string
	switch req.Action {
	case "revoke_default":
		obj, ok := pgDefaultACLObjects[req.ObjectType]
		if !ok {
			return nil, fmt.Errorf("invalid object type")
		}
		if !safeObjName(req.Owner) {
			return nil, fmt.Errorf("owner is required")
		}
		in := ""
		if req.Schema != "" {
			if !safeObjName(req.Schema) {
				return nil, fmt.Errorf("invalid schema")
			}
			in = " IN SCHEMA " + quoteIdentPG(req.Schema)
		}
		stmts = append(stmts, fmt.Sprintf("ALTER DEFAULT PRIVILEGES%s%s REVOKE ALL ON %s FROM %s", forRole(req.Owner), in, obj, user))

	case "revoke":
		if !safeObjName(req.Schema) {
			return nil, fmt.Errorf("schema is required")
		}
		s := quoteIdentPG(req.Schema)
		stmts = append(stmts, fmt.Sprintf("REVOKE ALL ON ALL TABLES IN SCHEMA %s FROM %s", s, user))
		if req.IncludeSequences {
			stmts = append(stmts, fmt.Sprintf("REVOKE ALL ON ALL SEQUENCES IN SCHEMA %s FROM %s", s, user))
		}
		if req.IncludeFuture {
			for _, r := range roles {
				stmts = append(stmts, fmt.Sprintf("ALTER DEFAULT PRIVILEGES%s IN SCHEMA %s REVOKE ALL ON TABLES FROM %s", forRole(r), s, user))
				if req.IncludeSequences {
					stmts = append(stmts, fmt.Sprintf("ALTER DEFAULT PRIVILEGES%s IN SCHEMA %s REVOKE ALL ON SEQUENCES FROM %s", forRole(r), s, user))
				}
			}
		}
		stmts = append(stmts, fmt.Sprintf("REVOKE ALL ON SCHEMA %s FROM %s", s, user))

	default: // grant
		if !safeObjName(req.Schema) {
			return nil, fmt.Errorf("schema is required")
		}
		tables, sequences := accessPresetPrivs("postgres", req)
		if len(tables) == 0 {
			return nil, fmt.Errorf("select at least one table privilege")
		}
		s := quoteIdentPG(req.Schema)
		stmts = append(stmts,
			fmt.Sprintf("GRANT CONNECT ON DATABASE %s TO %s", quoteIdentPG(db), user),
			fmt.Sprintf("GRANT USAGE ON SCHEMA %s TO %s", s, user),
			fmt.Sprintf("GRANT %s ON ALL TABLES IN SCHEMA %s TO %s", strings.Join(tables, ", "), s, user),
		)
		withSeq := req.IncludeSequences && len(sequences) > 0
		if withSeq {
			stmts = append(stmts, fmt.Sprintf("GRANT %s ON ALL SEQUENCES IN SCHEMA %s TO %s", strings.Join(sequences, ", "), s, user))
		}
		if req.IncludeFuture {
			for _, r := range roles {
				stmts = append(stmts, fmt.Sprintf("ALTER DEFAULT PRIVILEGES%s IN SCHEMA %s GRANT %s ON TABLES TO %s", forRole(r), s, strings.Join(tables, ", "), user))
				if withSeq {
					stmts = append(stmts, fmt.Sprintf("ALTER DEFAULT PRIVILEGES%s IN SCHEMA %s GRANT %s ON SEQUENCES TO %s", forRole(r), s, strings.Join(sequences, ", "), user))
				}
			}
		}
	}
	return []grantBatch{{Database: db, Statements: stmts}}, nil
}

func planMySQLAccess(username, host string, req dbAccessRequest) ([]grantBatch, error) {
	if !safeObjName(req.Database) {
		return nil, fmt.Errorf("database is required")
	}
	userSpec := fmt.Sprintf("'%s'@'%s'", escapeMySQL(username), escapeMySQL(host))
	target := mysqlGrantTarget("database", req.Database, "")
	switch req.Action {
	case "revoke":
		return []grantBatch{{Statements: []string{fmt.Sprintf("REVOKE ALL PRIVILEGES ON %s FROM %s", target, userSpec)}}}, nil
	case "", "grant":
		privs, _ := accessPresetPrivs("mysql", req)
		if len(privs) == 0 {
			return nil, fmt.Errorf("select at least one privilege")
		}
		return []grantBatch{{Statements: []string{fmt.Sprintf("GRANT %s ON %s TO %s", strings.Join(privs, ", "), target, userSpec)}}}, nil
	}
	return nil, fmt.Errorf("unsupported action for this driver")
}

// DBUserAccess handles POST /api/connections/{id}/db-users/{username}/access:
// schema-wide grant/revoke presets (PostgreSQL: USAGE + ALL TABLES/SEQUENCES IN
// SCHEMA + ALTER DEFAULT PRIVILEGES; MySQL: db.*), previewed, applied or sent
// for approval.
func DBUserAccess() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		connID, err := dbConnIDFromPath(r.URL.Path)
		if err != nil {
			http.Error(w, jsonError("invalid connection id"), http.StatusBadRequest)
			return
		}
		username := dbUsernameFromPath(r.URL.Path)
		if username == "" {
			http.Error(w, jsonError("missing username"), http.StatusBadRequest)
			return
		}
		var req dbAccessRequest
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			http.Error(w, jsonError("invalid request body"), http.StatusBadRequest)
			return
		}

		db, driver, err := GetDB(connID)
		if err != nil {
			http.Error(w, jsonError(err.Error()), http.StatusBadGateway)
			return
		}

		var batches []grantBatch
		title := ""
		switch driver {
		case "postgres":
			batches, err = planPGAccess(username, req, pgCurrentDatabase(r.Context(), db))
			scope := req.Schema
			if req.Database != "" {
				scope = req.Database + "." + req.Schema
			}
			switch req.Action {
			case "revoke":
				title = fmt.Sprintf("Revoke %s access to %s", username, scope)
			case "revoke_default":
				title = fmt.Sprintf("Revoke default privileges of %s", username)
			default:
				title = fmt.Sprintf("Grant %s access to %s", username, scope)
			}
		case "mysql", "mariadb":
			host := req.Host
			if host == "" {
				host = "%"
			}
			batches, err = planMySQLAccess(username, host, req)
			if req.Action == "revoke" {
				title = fmt.Sprintf("Revoke %s access to %s", username, req.Database)
			} else {
				title = fmt.Sprintf("Grant %s access to %s", username, req.Database)
			}
		default:
			http.Error(w, jsonError("unsupported driver"), http.StatusBadRequest)
			return
		}
		if err != nil {
			http.Error(w, jsonError(err.Error()), http.StatusBadRequest)
			return
		}
		respondDBAccessPlan(w, r, connID, db, driver, batches, req.dbAccessRequestOpts, title)
	}
}

