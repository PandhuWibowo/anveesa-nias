type DefaultPrivilegeEntry struct {
	Database   string   `json:"database"`
	Schema     string   `json:"schema"`
	Owner      string   `json:"owner"`
	ObjectType string   `json:"object_type"`
	Objects    string   `json:"objects"`
	Privileges []string `json:"privileges"`
}

// GetDBUserDefaultPrivileges handles GET .../db-users/{username}/default-privileges:
// ALTER DEFAULT PRIVILEGES entries that grant this user access to future objects.
func GetDBUserDefaultPrivileges() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		connID, err := dbConnIDFromPath(r.URL.Path)
		if err != nil {
			http.Error(w, jsonError("invalid connection id"), http.StatusBadRequest)
			return
		}
		username := dbUsernameFromPath(r.URL.Path)
		if username == "" {
			http.Error(w, jsonError("missing username"), http.StatusBadRequest)
			return
		}
		db, driver, err := GetDB(connID)
		if err != nil {
			http.Error(w, jsonError(err.Error()), http.StatusBadGateway)
			return
		}
		out := []DefaultPrivilegeEntry{}
		if driver != "postgres" {
			json.NewEncoder(w).Encode(out)
			return
		}

		var mu sync.Mutex
		pgForEachDatabase(r.Context(), connID, db, func(ctx context.Context, cdb *sql.DB, dbName string) {
			rows, err := cdb.QueryContext(ctx, `
				SELECT pg_get_userbyid(d.defaclrole),
				       COALESCE(n.nspname, ''),
				       d.defaclobjtype::text,
				       string_agg(DISTINCT a.privilege_type, ',')
				FROM pg_default_acl d
				LEFT JOIN pg_namespace n ON n.oid = d.defaclnamespace
				CROSS JOIN LATERAL aclexplode(d.defaclacl) a
				JOIN pg_roles g ON g.oid = a.grantee
				WHERE g.rolname = $1
				GROUP BY 1, 2, 3
			`, username)
			if err != nil {
				return
			}
			defer rows.Close()
			for rows.Next() {
				var e DefaultPrivilegeEntry
				var privs string
				if rows.Scan(&e.Owner, &e.Schema, &e.ObjectType, &privs) != nil {
					continue
				}
				e.Database = dbName
				e.Objects = pgDefaultACLObjects[e.ObjectType]
				for _, p := range strings.Split(privs, ",") {
					if p = strings.TrimSpace(p); p != "" {
						e.Privileges = append(e.Privileges, p)
					}
				}
				sort.Strings(e.Privileges)
				mu.Lock()
				out = append(out, e)
				mu.Unlock()
			}
		})
		sort.Slice(out, func(i, j int) bool {
			a, b := out[i], out[j]
			if a.Database != b.Database {
				return a.Database < b.Database
			}
			if a.Schema != b.Schema {
				return a.Schema < b.Schema
			}
			if a.Owner != b.Owner {
				return a.Owner < b.Owner
			}
			return a.ObjectType < b.ObjectType
		})
		json.NewEncoder(w).Encode(out)
	}
}

// ListSchemaOwnersForGrantPicker handles GET /api/connections/{id}/db-users-schema-owners?db=&schema=.
// ALTER DEFAULT PRIVILEGES only covers objects created by the named role, so
// the wizard offers the roles that own objects in the schema.
func ListSchemaOwnersForGrantPicker() http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		connID, err := dbConnIDFromPath(r.URL.Path)
		if err != nil {
			http.Error(w, jsonError("invalid connection id"), http.StatusBadRequest)
			return
		}
		schema := r.URL.Query().Get("schema")
		targetDB := r.URL.Query().Get("db")
		db, driver, err := GetDB(connID)
		if err != nil {
			http.Error(w, jsonError(err.Error()), http.StatusBadGateway)
			return
		}
		resp := map[string]any{"current_user": "", "schema_owner": "", "owners": []string{}}
		if driver != "postgres" || schema == "" {
			json.NewEncoder(w).Encode(resp)
			return
		}
		err = withConnDatabase(r.Context(), connID, db, driver, targetDB, func(cdb *sql.DB) error {
			var curUser, schemaOwner string
			_ = cdb.QueryRowContext(r.Context(), `SELECT current_user`).Scan(&curUser)
			_ = cdb.QueryRowContext(r.Context(), `SELECT pg_get_userbyid(nspowner) FROM pg_namespace WHERE nspname = $1`, schema).Scan(&schemaOwner)
			rows, err := cdb.QueryContext(r.Context(), `
				SELECT DISTINCT pg_get_userbyid(c.relowner)
				FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
				WHERE n.nspname = $1 AND c.relkind IN ('r','p','v','m','S','f')
				ORDER BY 1
			`, schema)
			owners := []string{}
			if err == nil {
				defer rows.Close()
				for rows.Next() {
					var o string
					if rows.Scan(&o) == nil && o != "" {
						owners = append(owners, o)
					}
				}
			}
			resp["current_user"] = curUser
			resp["schema_owner"] = schemaOwner
			resp["owners"] = owners
			return nil
		})
		if err != nil {
			http.Error(w, jsonError(err.Error()), http.StatusBadGateway)
			return
		}
		json.NewEncoder(w).Encode(resp)
	}
}
